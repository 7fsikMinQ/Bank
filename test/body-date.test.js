// 월 판정은 "문자 본문의 거래 일시(MM/DD HH:mm)"가 우선, 없으면 파일 시각. 1일 0시 ~ 말일 23:59 를 정확히 지킨다.
const assert = require("assert");
const { aggregate, bodyDateIso, daysInMonth } = require("../scriptable/ledger-core.js");
const W = "[Web발신]\n";
const sms = (md, hm, amt = 1000) => W + `BC바로(5678) 승인\n홍*동님\n${amt.toLocaleString()}원 일시불\n${md} ${hm}\n카페`;
const raw = (text, mtime, name = "Text.txt") => ({ name, text, mtime });
const bc = (items, now) => aggregate(items, now).sum.bc;

// 1 자동화가 늦게 실행돼 파일 시각이 다음 달이어도, 거래가 일어난 달로 들어간다
const late = raw(sms("10/31", "23:59", 9900), "2026-11-01T00:05:00+09:00");
assert.strictEqual(bc([late], "2026-10-31T23:59:30+09:00"), 9900);   // 10월 합계에 포함
assert.strictEqual(bc([late], "2026-11-01T09:00:00+09:00"), 0);       // 11월 합계에는 없음
// 반대: 1일 0시 직후 거래가 일찍(전날) 저장될 수는 없지만, 파일 시각이 틀려도 본문이 우선
assert.strictEqual(bc([raw(sms("11/01", "00:00", 500), "2026-10-31T23:59:59+09:00")], "2026-11-01T12:00:00+09:00"), 500);

// 2 연도 넘김: 12/31 23:50 거래가 1/1 00:10 에 저장 → 전년 12월
const dec = raw(sms("12/31", "23:50", 7000), "2027-01-01T00:10:00+09:00");
assert.strictEqual(bc([dec], "2026-12-31T23:55:00+09:00"), 7000);
assert.strictEqual(bc([dec], "2027-01-01T09:00:00+09:00"), 0);
// 1/1 00:00 거래는 새해 1월
assert.strictEqual(bc([raw(sms("01/01", "00:00", 300), "2027-01-01T00:00:05+09:00")], "2027-01-15T00:00:00+09:00"), 300);

// 3 모든 달 × (평년 2026, 윤년 2028): 말일 23:59 는 그 달, 다음 달 1일 00:00 은 다음 달
for (const year of [2026, 2028]) for (let m = 1; m <= 12; m++) {
  const last = daysInMonth(year, m), p2 = n => String(n).padStart(2, "0");
  const ny = m === 12 ? year + 1 : year, nm = m === 12 ? 1 : m + 1;
  const a = raw(sms(`${p2(m)}/${p2(last)}`, "23:59", 10), `${year}-${p2(m)}-${p2(last)}T23:59:30+09:00`);
  const b = raw(sms(`${p2(nm)}/01`, "00:00", 1000), `${ny}-${p2(nm)}-01T00:00:10+09:00`, "Text 1.txt");
  const f = raw(sms(`${p2(m)}/01`, "00:00", 100), `${year}-${p2(m)}-01T00:00:10+09:00`, "Text 2.txt");
  assert.strictEqual(bc([a, b, f], `${year}-${p2(m)}-${p2(last)}T23:59:59+09:00`), 110, `${year}-${m} 월말 시점`);
  assert.strictEqual(bc([a, b, f], `${ny}-${p2(nm)}-01T12:00:00+09:00`), 1000, `${ny}-${nm} 다음 달 시점`);
}

// 4 윤일: 2028-02-29 는 2월, 평년(2027) 02/29 는 존재하지 않는 날짜라 무시하고 파일 시각 사용
assert.strictEqual(bc([raw(sms("02/29", "10:00", 800), "2028-02-29T10:00:05+09:00")], "2028-02-29T12:00:00+09:00"), 800);
assert.strictEqual(bodyDateIso(sms("02/29", "10:00"), "2027-03-01T10:00:00+09:00"), "");      // 평년 → 무효
assert.strictEqual(bc([raw(sms("02/29", "10:00", 800), "2027-03-01T10:00:05+09:00")], "2027-03-02T00:00:00+09:00"), 800); // 파일 시각(3월)으로 처리

// 5 본문 일시가 파일 시각과 40일 넘게 어긋나면(옛 문자 재저장 등) 본문 일시를 믿지 않고 파일 시각 사용
assert.strictEqual(bodyDateIso(sms("08/25", "16:00"), "2026-10-08T09:00:00+09:00"), "");
// 6 일시가 없는 문자는 파일 시각 사용(기존 동작 유지) / 형식이 비슷한 가짜(9,900원 (10/08 사용) 등)는 오인하지 않음
assert.strictEqual(bc([raw(W + "BC바로(5678) 승인\n홍*동님\n3,000원 일시불\n카페", "2026-10-08T09:00:00+09:00")], "2026-10-08T12:00:00+09:00"), 3000);
assert.strictEqual(bodyDateIso(W + "BC바로(5678)승인취소\n9,900원 (10/08 사용)", "2026-10-08T09:00:00+09:00"), "");   // 시각 없는 "(10/08 사용)"은 일시로 보지 않음
// 7 시간대 독립(TZ 환경변수를 바꿔 반복 실행됨) + 헤더 방식 파일도 본문 일시 우선
assert.strictEqual(bc(["비씨\n2026-11-01T00:05:00+09:00\n" + sms("10/31", "23:59", 4000)], "2026-10-31T23:59:30+09:00"), 4000);
// 8 실제 4개 카드 문자 형식 모두 본문 일시를 읽는다
const real = [W+"우리카드(1234)체크승인\n홍*동님\n9,900원\n10/08 09:31\n무신사", W+"BC바로(5678) 승인\n홍*동님\n9,900원 일시불\n10/08 09:27\n무신사페이먼츠\n총누적1,120,900원",
              W+"현대 네이버 승인\n홍*동\n9,900원 일시불\n10/08 09:36\n무신사\n누적516,000원", W+"신한카드(9999)승인 홍*동 9,900원\n(일시불)10/08 09:40 무신사페이먼\n누적91,583원"];
for (const t of real) assert.strictEqual(bodyDateIso(t, "2026-10-08T12:00:00+09:00").slice(0, 16), "2026-10-08T" + (/09:31/.test(t) ? "00:31" : /09:27/.test(t) ? "00:27" : /09:36/.test(t) ? "00:36" : "00:40"));
console.log("BODY DATE OK (거래일시 기준 월 판정: 늦은 저장·연도 넘김·24개월 경계·윤일·시간대)");

// 9 중복 판정은 저장 시각 기준: 두 자동화가 같은 문자를 7초 간격으로 저장 → 1건 / 같은 문자가 2분 간격으로 저장(진짜 두 번 결제) → 2건
const one = sms("10/08", "09:31", 5000);
assert.strictEqual(bc([raw(one, "2026-10-08T09:31:05+09:00"), raw(one, "2026-10-08T09:31:12+09:00", "Text 1.txt")], "2026-10-08T12:00:00+09:00"), 5000);
assert.strictEqual(bc([raw(one, "2026-10-08T09:31:05+09:00"), raw(one, "2026-10-08T09:33:30+09:00", "Text 1.txt")], "2026-10-08T12:00:00+09:00"), 10000);
console.log("DEDUPE OK (저장 시각 기준)");

// 10 단축어 "하위 경로 = / + 현재 날짜(yyyyMMdd-HHmmss) + .txt" 로 저장한 문자 원문 파일: 이름의 시각 + 본문 일시, 늦은 저장·같은 분의 승인/취소
const dn = (name, text, mtime = "") => ({ name, text, mtime });
assert.strictEqual(bc([dn("20261031-235930.txt", sms("10/31", "23:59", 9900), "2026-11-01T00:05:00+09:00")], "2026-10-31T23:59:59+09:00"), 9900);   // 이름·본문 모두 10월
assert.strictEqual(bc([dn("20261101-000500.txt", sms("10/31", "23:59", 9900))], "2026-11-01T09:00:00+09:00"), 0);                                  // 늦게 저장(11/01 00:05)돼도 본문(10/31)이 우선 → 11월 합계에 없음
// 같은 분의 승인과 취소(이름이 초 단위로 달라 서로 다른 파일) → 둘 다 반영되어 순 0
const ap = sms("10/08", "09:31", 9900), ca = sms("10/08", "09:31", 9900).replace("승인", "승인취소");
assert.strictEqual(bc([dn("20261008-093105.txt", ap), dn("20261008-093112.txt", ca)], "2026-10-08T12:00:00+09:00"), 0);
console.log("DATE-NAMED FILES OK");
