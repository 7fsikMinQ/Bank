const assert = require("assert");
const { aggregate } = require("../scriptable/ledger-core.js");
const f = (s, iso, b) => `${s}\n${iso}\n${b}`;
const files = [
  f("1588-4000", "2026-10-02T03:00:00Z", "[BC카드] 승인 12,000원 일시불 스타벅스"),
  f("1588-4000", "2026-10-03T03:00:00Z", "[BC카드] 승인 30,000원 일시불 GS25"),
  f("1588-4000", "2026-10-04T03:00:00Z", "[BC카드] 승인취소 30,000원 GS25"),   // 전액취소
  f("1544-7000", "2026-10-05T03:00:00Z", "현대카드 ED3 승인 45,000원 네이버"),
  f("1544-7000", "2026-10-06T03:00:00Z", "현대카드 부분취소 5,000원 네이버"),   // 부분취소
  f("1544-7200", "2026-09-30T14:59:00Z", "신한카드 승인 99,000원"),            // KST 9/30 23:59 → 전월
  f("1544-7200", "2026-09-30T15:01:00Z", "신한카드 승인 10,000원"),            // KST 10/1 00:01 → 이번달
  f("1588-9999", "2026-10-06T03:00:00Z", "우리카드 해외승인 USD 10"),          // 금액 없음 → unparsed
  f("1588-9999", "2026-10-06T04:00:00Z", "우리카드 승인 7,000원"),
];
const r = aggregate(files, "2026-10-07T00:00:00Z");
assert.deepStrictEqual(r.sum, { bc: 12000, hd: 40000, sh: 10000, wr: 7000 });
assert.strictEqual(r.unparsed, 1);
console.log("OK", r);
